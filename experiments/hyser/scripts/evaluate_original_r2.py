#!/usr/bin/env python3
"""Evaluate neuro-style original_r2 and paired relative error on real Hyser.

Input generated by scripts/run_hard_distance_multiseed.py:
  output/domains.npz, output/hard_hiwa_original_multiseed_distance.json
This script computes metrics post hoc, never supplies known pairs to HiWA fitting.
"""
from pathlib import Path
import argparse, json
import numpy as np
from scipy.linalg import sqrtm, orthogonal_procrustes

def white(v):
    m=v-v.mean(axis=0,keepdims=True)
    root=np.real_if_close(sqrtm(np.cov(m,rowvar=False))).astype(float)
    return m @ np.linalg.pinv(root)

def neuro_r2(pred,truth):
    # Exact logic of src/cc_hiwa/common.py::original_r2, generalized to 3 dimensions.
    A=white(pred); B=white(truth)
    return float(1-np.mean((B-A)**2,axis=0).sum()/np.var(B,axis=0).sum())

def metrics(X,Y,R):
    pred=X@R.T
    delta=pred-Y
    relative_squared=float(np.linalg.norm(delta,'fro')**2/np.linalg.norm(Y,'fro')**2)
    pooled_R2=float(1-np.linalg.norm(delta,'fro')**2/np.linalg.norm(Y-Y.mean(axis=0),'fro')**2)
    return {'original_neural_R2':neuro_r2(pred,Y),
            'relative_squared_error':relative_squared,
            'relative_Frobenius_error':float(np.sqrt(relative_squared)),
            'pooled_standard_R2':pooled_R2,
            'mean_paired_euclidean_distance':float(np.mean(np.linalg.norm(delta,axis=1)))}

def fit_white(train):
    mean=train.mean(axis=0)
    eig,vec=np.linalg.eigh(np.cov(train,rowvar=False))
    W=(vec*np.maximum(eig,1e-8)**(-.5))@vec.T
    return mean,W

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--out-dir',type=Path,required=True)
    parser.add_argument('--run-json',type=Path)
    args=parser.parse_args()
    out=args.out_dir
    run_file=args.run_json or out/'hard_hiwa_original_multiseed_distance.json'
    run=json.loads(run_file.read_text())
    z=np.load(out/'domains.npz',allow_pickle=True)
    xm,xw=fit_white(z['Xtrain']);ym,yw=fit_white(z['Ytrain'])
    Xtr=(z['Xtrain']-xm)@xw;Ytr=(z['Ytrain']-ym)@yw
    Xte=(z['Xtest']-xm)@xw;Yte=(z['Ytest']-ym)@yw
    def locate(x_ids,y_ids):
        index={s:i for i,s in enumerate(y_ids)}
        return np.array([index[s] for s in x_ids])
    tr=locate(z['tr_pair'],z['tr_y_pair'])
    te=locate(z['te_pair'],z['te_y_pair'])
    train_truth,test_truth=Ytr[tr],Yte[te]
    oracle_row,_=orthogonal_procrustes(Xtr,train_truth)
    oracle=oracle_row.T
    identity=np.eye(3)
    outputs={'source':'Real Hyser trial1','code':'src/cc_hiwa/common.py::original_r2 formula',
      'warning':'This is not src/hiwa/hiwa.py rotation-rMSE: real Rgt does not exist.',
      'before':{'train':metrics(Xtr,train_truth,identity),'holdout':metrics(Xte,test_truth,identity)},
      'train_oracle':{'train':metrics(Xtr,train_truth,oracle),'holdout':metrics(Xte,test_truth,oracle)},
      'seeds':[]}
    for s in run['seeds']:
        R=np.asarray(s['R'],dtype=float)
        outputs['seeds'].append({'seed':s['seed'],'converged':s['converged'],
          'train':metrics(Xtr,train_truth,R),'holdout':metrics(Xte,test_truth,R)})
    output_file=out/'hard_hiwa_original_class_R2_relative_error.json'
    output_file.write_text(json.dumps(outputs,ensure_ascii=False,indent=2))
    print('saved',output_file)
if __name__=='__main__':main()
